//! Compiles the anchored fragments the walkthrough parity test asserts.
//!
//! A chapter quotes the statement the fragment it includes renders, and the
//! parity test compares the two. Rebuilding that statement from a transcription
//! of the fragment leaves one drift direction open: an edited fragment still
//! passes while the chapter keeps quoting the statement the old fragment
//! produced. The build script therefore reads the shipped fragment itself,
//! rewrites its execution terminal into the build terminal, and writes one
//! function per fragment into `OUT_DIR`, where the parity test includes the
//! module and calls the functions. An edit to an audited fragment now fails the
//! compilation of that module, the build script, or the SQL and quote
//! assertions instead of passing silently.
//!
//! The anchor grammar is the module the coverage guard reads, so the region this
//! script extracts is the region the guard counts.

use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

#[path = "src/anchors.rs"]
mod anchors;

/// The anchor grammar this script and the coverage guard read together.
const ANCHORS_MODULE: &str = "src/anchors.rs";

/// The module the script writes into `OUT_DIR`.
const GENERATED_MODULE: &str = "walkthrough_fragments.rs";

/// The wrapper the script writes into `OUT_DIR` around the generated-module
/// fixture.
const GENERATED_SCHEMA_MODULE: &str = "generated_schema_module.rs";

/// The fixture carrying the module the code generator emits.
const SCHEMA_MODULE_FIXTURE: &str = "generated/schema_module.rs";

/// The environment variable naming the directory the build script writes into.
const OUT_DIR: &str = "OUT_DIR";

/// The environment variable naming the root of the package.
const MANIFEST_DIR: &str = "CARGO_MANIFEST_DIR";

/// The terminals an asynchronous fragment ends in when it executes the statement
/// it builds.
///
/// A selection reports the rows it read, a single-row selection reports the one
/// row it read, and a mutation reports the rows it wrote; each of these executes
/// the statement, so a fragment ending in one of them is rebuilt into the build
/// terminal below. The list is the closed set of terminals this script
/// recognises, so an ending it does not name is reported instead of emitted: the
/// generated function holds no connection to execute the call against.
const EXECUTION_TERMINALS: &[&str] = &[
    ".fetch_all(&pool)",
    ".fetch_one(&pool)",
    ".execute(&pool)",
];
/// The `await` that follows the execution terminal of a fragment.
const AWAIT_TERMINAL: &str = ".await?;";

/// The terminal the generated function ends the same statement in.
const BUILD_TERMINAL: &str = ".build()?;";

/// The header every generated module opens with.
///
/// A fragment reads the scaffolding of the file it lives in, so the generated
/// module carries the same imports that file declares.
const HEADER: &str = concat!(
    "// Generated by `build.rs` from the anchored fragments of the examples.\n",
    "// Do not edit: edit the fragment the example carries instead.\n",
    "use rurqe::postgres::prelude::*;\n",
    "use rurqe::sqlite::sqlite3_35;\n",
    "use rurqe_examples::markers::*;\n",
);

/// One audited fragment: the example file carrying the region, the anchor naming
/// it, and the binding the region leaves the statement it builds in.
type Fragment = (&'static str, &'static str, &'static str);

/// Every anchored fragment a walkthrough quotes, as `(file, anchor, binding)`.
///
/// The list is the audit itself: a fragment the book quotes and this list omits
/// is a statement no test asserts.
const FRAGMENTS: &[Fragment] = &[
    ("dialects.rs", "postgres", "postgres_query"),
    ("dialects.rs", "sqlite", "sqlite_query"),
    ("dialects.rs", "jsonb", "documents"),
    ("dialects.rs", "arrays", "tagged"),
    ("dialects.rs", "regex", "matching"),
    ("dialects.rs", "for_update", "claimed"),
    ("nested.rs", "collection", "parents"),
    ("nested.rs", "named_collection", "named_parents"),
    ("nested.rs", "single", "parents_with_one"),
    ("nested.rs", "collection_sqlite", "statement"),
    ("joins.rs", "inner", "inner_join"),
    ("joins.rs", "outer", "outer_join"),
    ("aggregates.rs", "group_by", "per_user"),
    ("ordering.rs", "order_by", "page"),
    ("subqueries.rs", "scalar", "above_average"),
    ("subqueries.rs", "in_subquery", "with_orders"),
    ("crud.rs", "update", "updated"),
    ("crud.rs", "update_from", "linked"),
    ("crud.rs", "delete", "removed"),
    ("crud.rs", "delete_using", "cleaned"),
];

fn main() {
    if let Err(error) = generate() {
        eprintln!("the audited anchored fragments could not be compiled: {error}");
        std::process::exit(1);
    }
}

/// Writes the fragment module into `OUT_DIR` and declares the inputs that
/// invalidate it.
fn generate() -> Result<(), String> {
    let root = package_root()?;
    let mut module = String::from(HEADER);
    for &(file, anchor, binding) in FRAGMENTS {
        let source = read_example(&root, file)?;
        let region = region_of(file, anchor, &source)?;
        let statement = build_terminal(file, anchor, &region)?;
        module.push_str(&function(file, anchor, binding, &statement));
    }
    write_module(&module)?;
    wrap_schema_module(&root)?;
    declare_inputs();
    Ok(())
}

/// The root of the documentation example package.
fn package_root() -> Result<PathBuf, String> {
    let manifest = env::var(MANIFEST_DIR)
        .map_err(|error| format!("`{MANIFEST_DIR}` is unknown to the build script: {error}"))?;
    Ok(PathBuf::from(manifest))
}

/// The source of one example file.
fn read_example(root: &Path, file: &str) -> Result<String, String> {
    let path = root.join(file);
    fs::read_to_string(&path)
        .map_err(|error| format!("`{}` is not readable: {error}", path.display()))
}

/// Writes the generated module into the directory the build script owns.
fn write_module(module: &str) -> Result<(), String> {
    write_out_file(GENERATED_MODULE, module)
}

/// Writes `contents` into the `OUT_DIR` file called `name`.
fn write_out_file(name: &str, contents: &str) -> Result<(), String> {
    let directory = env::var(OUT_DIR)
        .map_err(|error| format!("`{OUT_DIR}` is unknown to the build script: {error}"))?;
    let path = Path::new(&directory).join(name);
    fs::write(&path, contents)
        .map_err(|error| format!("`{}` is not writable: {error}", path.display()))
}

/// Wraps the generated-module fixture into the module the compilation test
/// includes.
///
/// The fixture is a module body rather than a programme of its own: it opens
/// with inner doc comments and an inner attribute, declares the tables, the
/// enum, and the row records of one catalog, and nests the module of a
/// secondary schema inside itself. A body like that compiles only inside a
/// module, so the wrapper places it in one, and the test includes the wrapper
/// from `OUT_DIR`.
///
/// The fixture reaches the wrapper verbatim, anchor marker lines included: the
/// markers are comments, and copying them keeps the file that is compiled byte
/// for byte the file the book quotes. The allowance the wrapper adds covers the
/// row decoder the generator emits — it reads the first value of a row with
/// `.get(0)`, which the workspace lints as `get_first` — and it is written as an
/// inner attribute of the module, so the module carries a single attribute style
/// and the shipped text stays exactly as the generator writes it.
fn wrap_schema_module(root: &Path) -> Result<(), String> {
    let fixture = read_example(root, SCHEMA_MODULE_FIXTURE)?;

    let mut wrapper = String::from("// Generated by `build.rs` from `");
    wrapper.push_str(SCHEMA_MODULE_FIXTURE);
    wrapper.push_str("`.\n");
    wrapper.push_str("// Do not edit: edit the fixture the book quotes instead.\n");
    wrapper.push_str("pub mod schema_module {\n");
    // The allowance is an inner attribute of the module it governs: a lint
    // attribute on the module item itself would meet the inner attributes the
    // fixture carries — its `//!` documentation and its own
    // `allow(dead_code)` — and an item holding both styles at once is refused
    // by the compiler.
    wrapper.push_str("#![allow(clippy::get_first)]\n");
    wrapper.push_str(&fixture);
    if !fixture.ends_with('\n') {
        wrapper.push('\n');
    }
    wrapper.push_str("}\n");

    write_out_file(GENERATED_SCHEMA_MODULE, &wrapper)
}

/// Declares the inputs whose edit invalidates the generated module.
fn declare_inputs() {
    println!("cargo:rerun-if-changed={ANCHORS_MODULE}");
    // The generated-module fixture is copied into the wrapper above, so an edit
    // to it has to rebuild the module the compilation test includes.
    println!("cargo:rerun-if-changed={SCHEMA_MODULE_FIXTURE}");
    let mut files: BTreeSet<&str> = BTreeSet::new();
    for &(file, _, _) in FRAGMENTS {
        files.insert(file);
    }
    for file in files {
        println!("cargo:rerun-if-changed={file}");
    }
}

/// The lines of the `anchor` region of `file`, with the indentation of the
/// marker removed from every line.
fn region_of(file: &str, anchor: &str, source: &str) -> Result<String, String> {
    let mut region: Option<(usize, Vec<&str>)> = None;
    for line in source.lines() {
        let indent = line.len() - line.trim_start().len();
        match anchors::classify(line) {
            anchors::AnchorLine::Open(name) => {
                if name != anchor {
                    continue;
                }
                if region.is_some() {
                    return Err(format!("`{file}` opens the region `{anchor}` twice"));
                }
                region = Some((indent, Vec::new()));
            }
            anchors::AnchorLine::Close(name) => {
                if name != anchor {
                    continue;
                }
                let Some((indent, lines)) = region.take() else {
                    return Err(format!("`{file}` closes the region `{anchor}` before it opens"));
                };
                return Ok(dedent(indent, &lines));
            }
            anchors::AnchorLine::Malformed(directive) => {
                if region.is_some() {
                    return Err(format!(
                        "`{file}` carries the malformed directive `{directive}` in `{anchor}`"
                    ));
                }
            }
            anchors::AnchorLine::Text => {
                if let Some((_, lines)) = region.as_mut() {
                    lines.push(line);
                }
            }
        }
    }
    Err(format!("`{file}` never closes the region `{anchor}`"))
}

/// The region text with the indentation of its marker removed from every line.
fn dedent(indent: usize, lines: &[&str]) -> String {
    let mut text = String::new();
    for line in lines {
        text.push_str(strip_indent(line, indent));
        text.push('\n');
    }
    text.trim_end().to_owned()
}

/// `line` without its first `width` leading whitespace characters.
fn strip_indent(line: &str, width: usize) -> &str {
    for (skipped, (offset, character)) in line.char_indices().enumerate() {
        if skipped == width || !character.is_whitespace() {
            return &line[offset..];
        }
    }
    ""
}

/// Rewrites the execution terminal of `region` into the build terminal.
///
/// A fragment that ends in an execution terminal — `.fetch_all(&pool)` for a
/// selection, `.fetch_one(&pool)` for a single-row selection, `.execute(&pool)`
/// for a mutation — followed by `.await?;` runs the statement it builds, so the
/// generated function ends the same statement in `.build()?` instead. A region
/// that awaits a call the list above does not name is reported, because the
/// statement would otherwise reach the generated function with an execution call
/// it has no connection for. Any other ending is emitted verbatim and has to
/// compile as it stands.
fn build_terminal(file: &str, anchor: &str, region: &str) -> Result<String, String> {
    let statement = region.trim_end();
    if !statement.ends_with(AWAIT_TERMINAL) {
        return Ok(statement.to_owned());
    }
    let Some((terminal, start)) = EXECUTION_TERMINALS
        .iter()
        .filter_map(|terminal| statement.rfind(*terminal).map(|start| (*terminal, start)))
        .max_by_key(|&(_, start)| start)
    else {
        return Err(format!(
            "`{anchor}` of `{file}` ends in `{AWAIT_TERMINAL}` without one of {}",
            EXECUTION_TERMINALS.join(" / ")
        ));
    };
    let tail = &statement[start + terminal.len()..];
    if tail.trim() != AWAIT_TERMINAL {
        return Err(format!(
            "`{anchor}` of `{file}` carries `{}` between its statement and its await",
            tail.trim()
        ));
    }
    let mut rewritten = String::with_capacity(statement.len());
    rewritten.push_str(&statement[..start]);
    rewritten.push_str(BUILD_TERMINAL);
    Ok(rewritten)
}

/// The generated function of one fragment.
fn function(file: &str, anchor: &str, binding: &str, statement: &str) -> String {
    let name = function_name(file, anchor);
    let mut generated = format!("/// The `{anchor}` fragment of `{file}`.\n");
    generated.push_str(&format!("pub fn {name}() -> Result<BuiltQuery, BuildError> {{\n"));
    for line in statement.lines() {
        if line.trim().is_empty() {
            generated.push('\n');
        } else {
            generated.push_str("    ");
            generated.push_str(line);
            generated.push('\n');
        }
    }
    generated.push_str(&format!("    Ok({binding})\n}}\n\n"));
    generated
}

/// The name of the generated function of one fragment.
fn function_name(file: &str, anchor: &str) -> String {
    let stem = file.strip_suffix(".rs").unwrap_or(file);
    let name = format!("{stem}_{anchor}");
    name.replace(|character: char| !character.is_ascii_alphanumeric(), "_")
}
