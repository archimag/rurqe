fn main() {
    if let Err(error) = generate() {
        eprintln!("the audited anchored fragments could not be compiled: {error}");
        std::process::exit(1);
    }
}

/// Writes both generated modules into `OUT_DIR` and declares the inputs that
/// invalidate them.
fn generate() -> Result<(), String> {
    let root = package_root()?;
    let mut sources: BTreeMap<&'static str, String> = BTreeMap::new();
    for fragment in FRAGMENTS {
        if !sources.contains_key(fragment.file) {
            sources.insert(fragment.file, read_example(&root, fragment.file)?);
        }
    }
    write_out_file(AUDIT_MODULE, &audit_module())?;
    write_out_file(GENERATED_MODULE, &fragment_module(&sources)?)?;
    wrap_generated_modules(&root)?;
    declare_inputs();
    Ok(())
}

/// The audit registry, as the coverage guard reads it.
fn audit_module() -> String {
    let mut module = String::from(AUDIT_HEADER);
    for fragment in FRAGMENTS {
        let chapters = fragment
            .chapters
            .iter()
            .map(|chapter| format!("{chapter:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        module.push_str(&format!(
            "    Audited {{ file: {:?}, anchor: {:?}, chapters: &[{}] }},\n",
            fragment.file, fragment.anchor, chapters
        ));
    }
    module.push_str("];\n");
    module
}

/// The module of rebuilt fragments: one module per example file, and one
/// function per fragment inside it.
fn fragment_module(sources: &BTreeMap<&'static str, String>) -> Result<String, String> {
    let mut module = String::from(MODULE_HEADER);
    for (file, source) in sources {
        module.push_str(&file_module(file, source)?);
    }
    module.push_str(&builder_table());
    Ok(module)
}

/// The module of one example file, together with the functions rebuilding the
/// fragments it carries.
///
/// The file reaches the module verbatim, so the tables, aliases, and records its
/// anchored regions read are the declarations the file ships. The doc comment
/// and the lint allowance are inner attributes: the copied file opens with its
/// own `//!` documentation, and one item cannot carry inner and outer
/// attributes at once. The allowance is what a copy costs: the example's `main`
/// is compiled here and never called, so everything it alone reaches is dead
/// code inside this module.
fn file_module(file: &str, source: &str) -> Result<String, String> {
    let stem = module_name(file);
    let mut module = format!("pub mod {stem} {{\n");
    module.push_str(&format!(
        "    //! The `{file}` example, whose declarations the rebuilt fragments read.\n"
    ));
    module.push_str("    #![allow(dead_code, unused_imports, unused_mut, unused_variables)]\n");
    for line in source.lines() {
        module.push_str(line);
        module.push('\n');
    }
    module.push('\n');
    for fragment in FRAGMENTS.iter().filter(|fragment| fragment.file == file) {
        let region = region_of(file, fragment.anchor, source)?;
        let statement = statement_of(file, fragment, &region)?;
        module.push_str(&function(fragment, &statement));
    }
    module.push_str("}\n\n");
    Ok(module)
}

/// The table binding every audited fragment to the function rebuilding it.
fn builder_table() -> String {
    let mut table = String::from(
        "/// Every audited fragment together with the function rebuilding it.\n\
         pub const BUILDERS: &[(&str, &str, RebuiltFragment)] = &[\n",
    );
    for fragment in FRAGMENTS {
        let stem = module_name(fragment.file);
        table.push_str(&format!(
            "    ({:?}, {:?}, {stem}::build_{}),\n",
            fragment.file, fragment.anchor, fragment.anchor
        ));
    }
    table.push_str("];\n");
    table
}

/// The module a fragment of `file` lands in.
fn module_name(file: &str) -> &str {
    file.strip_suffix(".rs").unwrap_or(file)
}

/// The statement a fragment's region produces, in the shape the generated
/// function carries it.
fn statement_of(file: &str, fragment: &Fragment, region: &str) -> Result<String, String> {
    match fragment.terminal {
        Terminal::Executed => rewrite_execution(file, fragment.anchor, region),
        Terminal::Inspected => rewrite_inspection(file, fragment.anchor, region),
        Terminal::Published => rewrite_publication(file, fragment.anchor, region),
        Terminal::Built => require_ending(file, fragment.anchor, region, BUILD_TERMINAL),
        Terminal::Assembled => require_ending(file, fragment.anchor, region, ")?;")
            .map(|statement| format!("let {} = {statement}", fragment.binding)),
    }
}

/// Requires `region` to end in `ending`, so a declared terminal is verified
/// instead of assumed.
fn require_ending(file: &str, anchor: &str, region: &str, ending: &str) -> Result<String, String> {
    let statement = region.trim_end();
    if statement.ends_with(ending) {
        Ok(statement.to_owned())
    } else {
        Err(format!("`{anchor}` of `{file}` does not end in `{ending}`"))
    }
}

/// Rewrites the execution terminal of `region` into the build terminal.
///
/// A fragment that ends in an execution terminal — `.fetch_all(&pool)` for a
/// selection, `.fetch_one(&pool)` for a single-row selection, `.execute(&pool)`
/// for a mutation — followed by `.await?;` runs the statement it builds, so the
/// generated function ends the same statement in `.build()?` instead. The
/// statements after the awaited call consume the rows it read — the loop that
/// prints them, the markers addressed after them — and are not part of the
/// statement the chapter quotes, so the rebuilt fragment stops at the awaited
/// execution call. A region that awaits a call the list above does not name is
/// reported, because the statement would otherwise reach the generated function
/// with an execution call it has no connection for.
fn rewrite_execution(file: &str, anchor: &str, region: &str) -> Result<String, String> {
    let statement = region.trim_end();
    let Some((terminal, start)) = EXECUTION_TERMINALS
        .iter()
        .filter_map(|terminal| statement.rfind(*terminal).map(|start| (*terminal, start)))
        .max_by_key(|&(_, start)| start)
    else {
        return Err(format!(
            "`{anchor}` of `{file}` awaits none of {}",
            EXECUTION_TERMINALS.join(" / ")
        ));
    };
    let tail = &statement[start + terminal.len()..];
    let Some(rest) = after_call_arguments(tail) else {
        return Err(format!(
            "`{anchor}` of `{file}` carries `{}` after its execution terminal without closing \
             the argument list of the call",
            tail.trim()
        ));
    };
    if !rest.trim_start().starts_with(AWAIT_TERMINAL) {
        return Err(format!(
            "`{anchor}` of `{file}` carries `{}` between its statement and its await",
            rest.trim()
        ));
    }
    let mut rewritten = String::with_capacity(start + BUILD_TERMINAL.len());
    rewritten.push_str(&statement[..start]);
    rewritten.push_str(BUILD_TERMINAL);
    Ok(rewritten)
}

/// Rewrites the publication a fragment ends in into the build terminal.
///
/// A fragment that ends by publishing its statement — `.as_cte::<UserTotals>()`
/// for a common table expression, and the derived-table and lateral siblings of
/// that call — hands the finished statement to another statement instead of
/// running it, so the statement the chapter quotes is the one the publication
/// wraps. The remainder after the call has to be the end of the fragment, which
/// is what keeps a mis-declared entry from silently truncating a chain.
fn rewrite_publication(file: &str, anchor: &str, region: &str) -> Result<String, String> {
    let statement = region.trim_end();
    let Some(start) = PUBLICATION_TERMINALS
        .iter()
        .filter_map(|terminal| statement.rfind(*terminal))
        .max()
    else {
        return Err(format!(
            "`{anchor}` of `{file}` publishes no statement, so there is nothing to build"
        ));
    };
    let remainder = &statement[start..];
    if remainder.matches(';').count() != 1 || !remainder.ends_with(';') {
        return Err(format!(
            "`{anchor}` of `{file}` carries `{}` after its publication, which is not the end \
             of the fragment",
            remainder.trim()
        ));
    }
    let mut rewritten = String::with_capacity(statement.len());
    rewritten.push_str(&statement[..start]);
    rewritten.push_str(BUILD_TERMINAL);
    Ok(rewritten)
}

/// Rewrites the awaited call a fragment inspects into the build terminal.
///
/// A fragment that inspects its outcome binds the awaited call and matches on
/// the value it produced, so the chapter it belongs to documents how a refusal
/// is read rather than the rows a statement wrote. The rebuilt function ends
/// the same statement in `.build()?` and drops the inspection that follows the
/// awaited call: the value the inspection reads is never produced here.
fn rewrite_inspection(file: &str, anchor: &str, region: &str) -> Result<String, String> {
    let statement = region.trim_end();
    let Some((terminal, start)) = EXECUTION_TERMINALS
        .iter()
        .filter_map(|terminal| statement.rfind(*terminal).map(|start| (*terminal, start)))
        .max_by_key(|&(_, start)| start)
    else {
        return Err(format!(
            "`{anchor}` of `{file}` awaits none of {}",
            EXECUTION_TERMINALS.join(" / ")
        ));
    };
    let tail = &statement[start + terminal.len()..];
    let Some(rest) = after_call_arguments(tail) else {
        return Err(format!(
            "`{anchor}` of `{file}` carries `{}` after its execution terminal without closing \
             the argument list of the call",
            tail.trim()
        ));
    };
    if !rest.trim_start().starts_with(AWAIT_INSPECTED) {
        return Err(format!(
            "`{anchor}` of `{file}` carries `{}` between its statement and its inspected await",
            rest.trim()
        ));
    }
    let mut rewritten = String::with_capacity(start + BUILD_TERMINAL.len());
    rewritten.push_str(&statement[..start]);
    rewritten.push_str(BUILD_TERMINAL);
    Ok(rewritten)
}

/// The generated function of one fragment.
fn function(fragment: &Fragment, statement: &str) -> String {
    let name = fragment.anchor;
    // The rebuilt function is prefixed so it cannot shadow an item the copied
    // example imports: an anchor called `update` would otherwise bind the entry
    // point the fragment itself calls, and the generated module would not build.
    let generated_name = format!("build_{name}");
    let mut generated = format!("    /// The `{name}` fragment.\n");
    generated.push_str(&format!(
        "    pub fn {generated_name}() -> Result<BuiltQuery, super::FragmentError> {{\n"
    ));
    for line in statement.lines() {
        if line.trim().is_empty() {
            generated.push('\n');
        } else {
            generated.push_str("        ");
            generated.push_str(line);
            generated.push('\n');
        }
    }
    generated.push_str("        ");
    generated.push_str(&epilogue(fragment));
    generated.push('\n');
    generated.push_str("    }\n\n");
    generated
}

/// The expression a rebuilt function hands its statement back through.
fn epilogue(fragment: &Fragment) -> String {
    match fragment.terminal {
        Terminal::Assembled => format!("Ok({}.build()?)", fragment.binding),
        _ => format!("Ok({})", fragment.binding),
    }
}

/// The root of the documentation example package.
fn package_root() -> Result<PathBuf, String> {
    let manifest = env::var(MANIFEST_DIR)
        .map_err(|error| format!("`{MANIFEST_DIR}` is unknown to the build script: {error}"))?;
    Ok(PathBuf::from(manifest))
}

/// The source of one example file.
fn read_example(root: &Path, file: &str) -> Result<String, String> {
    let path = root.join(file);
    fs::read_to_string(&path)
        .map_err(|error| format!("`{}` is not readable: {error}", path.display()))
}

/// Writes `contents` into the `OUT_DIR` file called `name`.
fn write_out_file(name: &str, contents: &str) -> Result<(), String> {
    let directory = env::var(OUT_DIR)
        .map_err(|error| format!("`{OUT_DIR}` is unknown to the build script: {error}"))?;
    let path = Path::new(&directory).join(name);
    fs::write(&path, contents)
        .map_err(|error| format!("`{}` is not writable: {error}", path.display()))
}

/// Wraps every generated-module fixture into the module the compilation tests
/// include.
fn wrap_generated_modules(root: &Path) -> Result<(), String> {
    for &(fixture, wrapper) in GENERATED_MODULE_FIXTURES {
        wrap_generated_module(root, fixture, wrapper)?;
    }
    Ok(())
}

/// Wraps one generated-module fixture into the module the compilation test
/// includes.
///
/// The fixture is a module body rather than a programme of its own: it opens
/// with inner doc comments and an inner attribute, declares the tables, the
/// enum, and the row records of one catalog, and nests the module of a
/// secondary schema inside itself when the catalog declares one. A body like
/// that compiles only inside a module, so the wrapper places it in one named
/// after the fixture, and the test includes the wrapper from `OUT_DIR`.
///
/// The fixture reaches the wrapper verbatim, anchor marker lines included: the
/// markers are comments, and copying them keeps the file that is compiled byte
/// for byte the file the book quotes. The wrapper adds no lint allowance and no
/// other attribute of its own, so the module a test compiles carries exactly the
/// attributes the generator emits and the shipped text stays as it is written.
fn wrap_generated_module(root: &Path, fixture: &str, wrapper_file: &str) -> Result<(), String> {
    let body = read_example(root, fixture)?;
    let path = Path::new(fixture);
    let module = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .ok_or_else(|| format!("`{fixture}` is not a `.rs` file"))?;

    let mut wrapper = String::from("// Generated by `build.rs` from `");
    wrapper.push_str(fixture);
    wrapper.push_str("`.\n");
    wrapper.push_str("// Do not edit: edit the fixture the book quotes instead.\n");
    wrapper.push_str("pub mod ");
    wrapper.push_str(module);
    wrapper.push_str(" {\n");
    wrapper.push_str(&body);
    if !body.ends_with('\n') {
        wrapper.push('\n');
    }
    wrapper.push_str("}\n");

    write_out_file(wrapper_file, &wrapper)
}

/// Declares the inputs whose edit invalidates the generated modules.
fn declare_inputs() {
    println!("cargo:rerun-if-changed={ANCHORS_MODULE}");
    // Every generated-module fixture is copied into its wrapper above, so an
    // edit to one has to rebuild the module the compilation tests include.
    for &(fixture, _) in GENERATED_MODULE_FIXTURES {
        println!("cargo:rerun-if-changed={fixture}");
    }
    // The embedded-migration example bakes the configuration of this directory
    // and the migration scripts that configuration names. A build script is the
    // only place that can register a directory's membership, so a script added
    // there or removed from it rebuilds the target that carries it.
    println!("cargo:rerun-if-changed={EXAMPLE_FIXTURES}");
    let mut files: BTreeSet<&str> = BTreeSet::new();
    for fragment in FRAGMENTS {
        files.insert(fragment.file);
    }
    for file in files {
        println!("cargo:rerun-if-changed={file}");
    }
}

/// The lines of the `anchor` region of `file`, with the indentation of the
/// marker removed from every line.
fn region_of(file: &str, anchor: &str, source: &str) -> Result<String, String> {
    let mut region: Option<(usize, Vec<&str>)> = None;
    for line in source.lines() {
        let indent = line.len() - line.trim_start().len();
        match anchors::classify(line) {
            anchors::AnchorLine::Open(name) => {
                if name != anchor {
                    continue;
                }
                if region.is_some() {
                    return Err(format!("`{file}` opens the region `{anchor}` twice"));
                }
                region = Some((indent, Vec::new()));
            }
            anchors::AnchorLine::Close(name) => {
                if name != anchor {
                    continue;
                }
                let Some((indent, lines)) = region.take() else {
                    return Err(format!(
                        "`{file}` closes the region `{anchor}` before it opens"
                    ));
                };
                return Ok(dedent(indent, &lines));
            }
            anchors::AnchorLine::Malformed(directive) => {
                if region.is_some() {
                    return Err(format!(
                        "`{file}` carries the malformed directive `{directive}` in `{anchor}`"
                    ));
                }
            }
            anchors::AnchorLine::Text => {
                if let Some((_, lines)) = region.as_mut() {
                    lines.push(line);
                }
            }
        }
    }
    Err(format!("`{file}` never closes the region `{anchor}`"))
}

/// The region text with the indentation of its marker removed from every line.
fn dedent(indent: usize, lines: &[&str]) -> String {
    let mut text = String::new();
    for line in lines {
        text.push_str(strip_indent(line, indent));
        text.push('\n');
    }
    text.trim_end().to_owned()
}

/// `line` without its first `width` leading whitespace characters.
fn strip_indent(line: &str, width: usize) -> &str {
    for (skipped, (offset, character)) in line.char_indices().enumerate() {
        if skipped == width || !character.is_whitespace() {
            return &line[offset..];
        }
    }
    ""
}
