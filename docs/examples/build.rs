//! Compiles the anchored fragments the walkthrough parity test asserts.
//!
//! A chapter quotes the statement the fragment it includes renders, and the
//! parity test compares the two. Rebuilding that statement from a transcription
//! of the fragment leaves one drift direction open: an edited fragment still
//! passes while the chapter keeps quoting the statement the old fragment
//! produced. The build script therefore reads the shipped fragment itself,
//! rewrites its terminal into the build terminal, and writes one function per
//! fragment into `OUT_DIR`, where the parity test includes the module and calls
//! the functions. An edit to an audited fragment now fails the compilation of
//! that module, the build script, or the SQL and quote assertions instead of
//! passing silently.
//!
//! The module a fragment lands in carries the example file the fragment lives
//! in: an anchored region names tables, aliases, and records that its file
//! declares outside every anchor, and copying the file is what keeps those
//! declarations without transcribing them either. The attributes on that module
//! are the price of the copy — the example's `main` is compiled here and never
//! called.
//!
//! The registry is published a second time as plain data, so the coverage guard
//! pairs every `sql` block of the book with the fragments the audit rebuilds
//! without compiling a single statement.
//!
//! The anchor grammar is the module the coverage guard reads, so the region this
//! script extracts is the region the guard counts.

