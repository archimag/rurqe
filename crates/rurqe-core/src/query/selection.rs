//! Projection targets, selections, and nullability lifting for query rows.

use core::marker::PhantomData;

use crate::dialect::SupportsAggregateFilter;
use crate::expr::{Aggregate, DialectInScope, Expr, ExprKind, FilteredAggregate, NonAggregate};
use crate::schema::{Column, ColumnBelongsTo, ExprInScope, Table};

use super::scope::{NonNullableRel, NullableRel, ScopePositions, TableNullabilityInScope};

/// A single item projected by a `SELECT` query, such as a column or a window expression.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a valid projection item",
    label = "must be a column, nullable column, or window expression",
    note = "columns, nullable columns, and window expressions (`.over(...)`) can be projected in a selection"
)]
pub trait SelectTarget {
    /// The Rust type produced for this projection.
    type RustType;

    /// Pushes the identifier name of this target if it is a simple column reference.
    fn push_column_name(&self, out: &mut Vec<&'static str>) {
        let _ = out;
    }

    /// Builds the dialect-neutral AST node this target renders into.
    ///
    /// The node describes the projection as plain data, so the surrounding
    /// statement is assembled and rendered from the AST exactly like every other
    /// expression node, without a rendering path of its own.
    fn to_expr_kind(&self) -> ExprKind;
}

impl<C: Column> SelectTarget for C {
    type RustType = C::RustType;

    fn push_column_name(&self, out: &mut Vec<&'static str>) {
        out.push(C::NAME);
    }

    fn to_expr_kind(&self) -> ExprKind {
        C::expr_kind()
    }
}

impl<T: 'static + Send + Sync, Scope: 'static + Send + Sync, Aggr, D> SelectTarget
    for Expr<T, Scope, Aggr, D>
{
    type RustType = T;

    fn to_expr_kind(&self) -> ExprKind {
        self.kind().clone()
    }
}

/// Statically asserts that the aggregation marker `Self` is renderable on the dialect `D`.
///
/// A filtered aggregate renders as `SUM("total") FILTER (WHERE ...)`, the
/// `FILTER` clause being an optional feature of SQL:2011 that an engine may not
/// implement. The capability is recorded by
/// [`SupportsAggregateFilter`](crate::dialect::SupportsAggregateFilter), so a
/// statement carrying a filtered aggregate compiles only on a dialect whose
/// engine can render it, and is rejected at the call site that embeds the
/// expression rather than by the database at execution time.
///
/// An unfiltered aggregate, and an expression that aggregates nothing, render on
/// every dialect.
#[diagnostic::on_unimplemented(
    message = "`{Self}` cannot be rendered by this dialect",
    label = "the dialect does not support this aggregation",
    note = "a filtered aggregate renders `FILTER (WHERE ...)`, so it needs a dialect implementing `SupportsAggregateFilter`"
)]
pub trait AggregateInDialect<D> {}

impl<D> AggregateInDialect<D> for NonAggregate {}

impl<D> AggregateInDialect<D> for Aggregate {}

impl<D: SupportsAggregateFilter> AggregateInDialect<D> for FilteredAggregate {}

/// Lifts a Rust value type into its nullable form.
///
/// Projecting a column from the nullable side of an outer join reaches the query
/// row in its nullable form, so the row type names `Option<T>` instead of `T`
/// and consuming code has to handle the absent value explicitly. The trait is
/// implemented for every scalar the SQL value surface supports — integers,
/// floating point numbers, booleans, text, and blobs — for the optional form
/// `Option<T>` itself, for `UUID`, temporal, and JSON values when their cargo
/// features are enabled, and for domain newtypes generated by the `sql_type`
/// derive macro, which forwards the nullability of the representation the
/// newtype wraps.
///
/// `LEFT JOIN` and `LEFT JOIN LATERAL` lift every column of the joined relation:
///
/// ```
/// use rurqe_core::dialect::Dialect;
/// use rurqe_core::expr::Expr;
/// use rurqe_core::query::{HasProjection, SelectQuery};
///
/// struct MockDialect;
///
/// impl Dialect for MockDialect {
///     fn push_quoted_identifier(out: &mut String, ident: &str) {
///         out.push_str(ident);
///     }
///
///     fn push_placeholder(out: &mut String, index: usize) {
///         let _ = index;
///     }
/// }
///
/// rurqe_core::table! {
///     User => "users" {
///         UserId => "id": i64,
///     }
/// }
///
/// rurqe_core::table! {
///     Order => "orders" {
///         OrderUserId => "user_id": i64,
///         OrderTotal => "total": f64,
///     }
/// }
///
/// fn main() {
///     let query = SelectQuery::<MockDialect>::new()
///         .from::<User>()
///         .left_join::<Order, _, _>(
///             Expr::column::<OrderUserId>().eq(Expr::column::<UserId>()),
///         )
///         .select((UserId, OrderTotal));
///
///     // `OrderTotal` is read from the nullable side of the join, so the row
///     // keeps it as `Option<f64>` while `UserId` stays a plain `i64`.
///     let _: SelectQuery<MockDialect, _, (i64, Option<f64>), HasProjection> = query;
/// }
/// ```
///
/// Reading the same column as a plain `f64` is rejected at compile time:
///
/// ```compile_fail
/// # use rurqe_core::dialect::Dialect;
/// # use rurqe_core::expr::Expr;
/// # use rurqe_core::query::{HasProjection, SelectQuery};
/// #
/// # struct MockDialect;
/// #
/// # impl Dialect for MockDialect {
/// #     fn push_quoted_identifier(out: &mut String, ident: &str) {
/// #         out.push_str(ident);
/// #     }
/// #
/// #     fn push_placeholder(out: &mut String, index: usize) {
/// #         let _ = index;
/// #     }
/// # }
/// #
/// # rurqe_core::table! {
/// #     User => "users" {
/// #         UserId => "id": i64,
/// #     }
/// # }
/// #
/// # rurqe_core::table! {
/// #     Order => "orders" {
/// #         OrderUserId => "user_id": i64,
/// #         OrderTotal => "total": f64,
/// #     }
/// # }
/// #
/// fn main() {
///     let query = SelectQuery::<MockDialect>::new()
///         .from::<User>()
///         .left_join::<Order, _, _>(
///             Expr::column::<OrderUserId>().eq(Expr::column::<UserId>()),
///         )
///         .select((UserId, OrderTotal));
///
///     // Fails to compile: the left-joined `OrderTotal` reaches the row as
///     // `Option<f64>`, so the row cannot be read as a plain `f64`.
///     let _: SelectQuery<MockDialect, _, (i64, f64), HasProjection> = query;
/// }
/// ```
#[diagnostic::on_unimplemented(
    message = "`{Self}` has no nullable form",
    label = "the column type cannot be lifted into `Option<{Self}>`",
    note = "implement `MakeNullable` for the column type to project it from an outer join"
)]
pub trait MakeNullable {
    /// The nullable representation of the type.
    type Nullable;
}

macro_rules! impl_make_nullable {
    ($($scalar:ty),+) => {
        $(
            impl MakeNullable for $scalar {
                type Nullable = Option<$scalar>;
            }
        )+
    };
}

impl_make_nullable!(i16, i32, u32, i64, usize, f64, bool, String, Vec<u8>);

impl<T> MakeNullable for Option<T> {
    type Nullable = Option<T>;
}

#[cfg(feature = "uuid")]
impl MakeNullable for uuid::Uuid {
    type Nullable = Option<uuid::Uuid>;
}

#[cfg(feature = "chrono")]
impl MakeNullable for chrono::NaiveDateTime {
    type Nullable = Option<chrono::NaiveDateTime>;
}

#[cfg(feature = "chrono")]
impl MakeNullable for chrono::DateTime<chrono::Utc> {
    type Nullable = Option<chrono::DateTime<chrono::Utc>>;
}

#[cfg(feature = "chrono")]
impl MakeNullable for chrono::NaiveDate {
    type Nullable = Option<chrono::NaiveDate>;
}

#[cfg(feature = "serde_json")]
impl MakeNullable for serde_json::Value {
    type Nullable = Option<serde_json::Value>;
}

