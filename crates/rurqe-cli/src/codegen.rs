//! Deterministic code generator for RURQE schema markers and strongly typed DTO records.
//!
//! Generates idiomatic Rust code containing:
//! - Compile-time schema fingerprint constant: `pub const SCHEMA_HASH: &str = "...";`
//! - Zero-cost schema markers via [`rurqe::table!`]
//! - Strongly typed `Record` structs with `FromRow` implementations

use rurqe_migrate::catalog::{ColumnDef, SchemaCatalog, TableDef, TypeKind};

/// Options controlling code generation.
#[derive(Debug, Clone)]
pub struct CodegenOptions {
    /// Module doc comment prepended to the generated output.
    pub doc_comment: Option<String>,
    /// Whether to generate strongly typed `*Record` structs for each table.
    pub generate_records: bool,
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            doc_comment: Some(
                "Automatically generated by RURQE. DO NOT EDIT DIRECTLY.\n\n\
                 To synchronize with the database catalog, run `cargo db-codegen`."
                    .to_owned(),
            ),
            generate_records: true,
        }
    }
}

/// Generates Rust schema source code from an engine-neutral [`SchemaCatalog`].
pub fn generate_schema_rs(catalog: &SchemaCatalog, options: &CodegenOptions) -> String {
    let mut out = String::new();

    if let Some(ref doc) = options.doc_comment {
        for line in doc.lines() {
            if line.is_empty() {
                out.push_str("//!\n");
            } else {
                out.push_str("//! ");
                out.push_str(line);
                out.push('\n');
            }
        }
        out.push('\n');
    }

    out.push_str("#![allow(dead_code)]\n\n");
    out.push_str("use rurqe::prelude::*;\n\n");

    // Embed the deterministic SHA-256 schema hash
    out.push_str(&catalog.hash_const());
    out.push_str("\n\n");

    let mut tables: Vec<&TableDef> = catalog.tables.iter().collect();
    tables.sort_by(|a, b| a.name.cmp(&b.name));

    for table in &tables {
        let table_ident = to_pascal_case(&table.name);

        out.push_str("table! {\n");
        out.push_str("    /// The `");
        out.push_str(&table.name);
        out.push_str("` table.\n");
        out.push_str("    ");
        out.push_str(&table_ident);
        out.push_str(" => \"");
        out.push_str(&table.name);
        out.push_str("\" {\n");

        let mut columns: Vec<&ColumnDef> = table.columns.iter().collect();
        columns.sort_by(|a, b| a.name.cmp(&b.name));

        for column in &columns {
            let col_ident = format!("{}{}", table_ident, to_pascal_case(&column.name));
            let rust_type = type_kind_to_rust_type(&column.type_kind, column.nullable);

            out.push_str("        ");
            out.push_str(&col_ident);
            out.push_str(" => \"");
            out.push_str(&column.name);
            out.push_str("\": ");
            out.push_str(&rust_type);
            out.push_str(",\n");
        }

        out.push_str("    }\n");
        out.push_str("}\n\n");

        if options.generate_records {
            let record_ident = format!("{}Record", table_ident);
            out.push_str("/// Strongly typed row record for `");
            out.push_str(&table.name);
            out.push_str("`.\n");
            out.push_str("#[derive(Debug, Clone, PartialEq)]\n");
            out.push_str("pub struct ");
            out.push_str(&record_ident);
            out.push_str(" {\n");

            for column in &columns {
                let field_name = to_safe_ident(&column.name);
                let rust_type = type_kind_to_rust_type(&column.type_kind, column.nullable);

                out.push_str("    pub ");
                out.push_str(&field_name);
                out.push_str(": ");
                out.push_str(&rust_type);
                out.push_str(",\n");
            }
            out.push_str("}\n\n");

            out.push_str("impl FromRow for ");
            out.push_str(&record_ident);
            out.push_str(" {\n");
            out.push_str("    fn from_row(values: &[SqlVal]) -> Option<Self> {\n");
            out.push_str("        if values.len() != ");
            out.push_str(&columns.len().to_string());
            out.push_str(" {\n");
            out.push_str("            return None;\n");
            out.push_str("        }\n");
            out.push_str("        Some(Self {\n");

            for (idx, column) in columns.iter().enumerate() {
                let field_name = to_safe_ident(&column.name);
                out.push_str("            ");
                out.push_str(&field_name);
                out.push_str(": FromSqlValue::from_sql_value(&values[");
                out.push_str(&idx.to_string());
                out.push_str("])?,\n");
            }

            out.push_str("        })\n");
            out.push_str("    }\n");
            out.push_str("}\n\n");
        }
    }

    out
}

fn type_kind_to_rust_type(kind: &TypeKind, nullable: bool) -> String {
    let base = match kind {
        TypeKind::Boolean => "bool",
        TypeKind::Int32 => "i32",
        TypeKind::Int64 => "i64",
        TypeKind::Float64 => "f64",
        TypeKind::Text => "String",
        TypeKind::Bytes => "Vec<u8>",
        TypeKind::Uuid => "String",
        TypeKind::Json => "String",
        TypeKind::Timestamp => "String",
        TypeKind::Date => "String",
        TypeKind::Other(_) => "String",
    };

    if nullable {
        format!("Option<{base}>")
    } else {
        base.to_owned()
    }
}

/// Converts an identifier (e.g., `user_profiles`) to PascalCase (`UserProfiles`).
pub fn to_pascal_case(s: &str) -> String {
    let mut out = String::new();
    let mut capitalize = true;

    for c in s.chars() {
        if c == '_' || c == '-' || c == ' ' {
            capitalize = true;
        } else if capitalize {
            out.extend(c.to_uppercase());
            capitalize = false;
        } else {
            out.push(c);
        }
    }

    if out.is_empty() {
        "Anonymous".to_owned()
    } else {
        out
    }
}

/// Converts a column identifier to a safe Rust field identifier, prefixing raw identifiers if reserved.
pub fn to_safe_ident(s: &str) -> String {
    let snake: String = s
        .chars()
        .map(|c| if c == '-' || c == ' ' { '_' } else { c.to_ascii_lowercase() })
        .collect();

    const RESERVED: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
        "use", "where", "while", "async", "await", "dyn",
    ];

    if RESERVED.contains(&snake.as_str()) {
        format!("r#{snake}")
    } else {
        snake
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use rurqe_migrate::catalog::{ColumnDef, TableDef, TypeKind};

    #[test]
    fn codegen_renders_deterministic_schema() {
        let catalog = SchemaCatalog::new(vec![TableDef::new(
            "users",
            vec![
                ColumnDef::new("id", TypeKind::Int64, false),
                ColumnDef::new("name", TypeKind::Text, false),
                ColumnDef::new("email", TypeKind::Text, true),
            ],
            vec!["id".to_owned()],
        )]);

        let code = generate_schema_rs(&catalog, &CodegenOptions::default());

        assert!(code.contains("pub const SCHEMA_HASH: &str = "));
        assert!(code.contains("Users => \"users\""));
        assert!(code.contains("UsersId => \"id\": i64"));
        assert!(code.contains("UsersEmail => \"email\": Option<String>"));
        assert!(code.contains("pub struct UsersRecord"));
        assert!(code.contains("impl FromRow for UsersRecord"));
    }

    #[test]
    fn reserved_keywords_are_escaped() {
        assert_eq!(to_safe_ident("type"), "r#type");
        assert_eq!(to_safe_ident("match"), "r#match");
        assert_eq!(to_safe_ident("name"), "name");
    }

    #[test]
    fn pascal_casing() {
        assert_eq!(to_pascal_case("user_orders"), "UserOrders");
        assert_eq!(to_pascal_case("users"), "Users");
    }
}
