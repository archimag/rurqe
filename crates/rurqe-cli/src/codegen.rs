//! Deterministic code generator for RURQE schema markers and strongly typed DTO records.
//!
//! Generates idiomatic Rust code containing:
//! - Compile-time schema fingerprint constant: `pub const SCHEMA_HASH: &str = "...";`
//! - Zero-cost schema markers via [`rurqe::table!`]
//! - Strongly typed `Record` structs with `FromRow` implementations
//!
//! Generation runs in three stages: the `naming` module sanitizes schema names
//! into valid Rust identifiers, the `plan` module assigns those identifiers to
//! every generated item and rejects collisions, and the `render` module turns
//! the plan into source text. A catalog therefore either renders into a
//! compilable module or is rejected with [`CodegenError::IdentifierCollision`].

use std::collections::BTreeMap;
use std::fmt;

mod naming;
mod plan;
mod render;

pub use self::naming::{to_pascal_case, to_safe_ident};
pub use self::render::generate_schema_rs;

/// Options controlling code generation.
#[derive(Debug, Clone)]
pub struct CodegenOptions {
    /// Module doc comment prepended to the generated output.
    pub doc_comment: Option<String>,
    /// Whether to generate strongly typed `*Record` structs for each table.
    pub generate_records: bool,
    /// Rust types keyed by their `table.column` schema path.
    ///
    /// An override replaces the mapped type of a column, so domain newtypes
    /// survive code generation. See [`crate::config`].
    pub type_overrides: BTreeMap<String, String>,
    /// Whether `Uuid`, `Json`, `Timestamp`, and `Date` columns map onto their
    /// domain types instead of `String`.
    ///
    /// The default mapping keeps the generated module compilable without extra
    /// dependencies, so the domain mapping is opt-in: enabling it makes the
    /// generated module require the `uuid`, `chrono`, and `serde_json` features
    /// of the `rurqe` facade.
    pub domain_types: bool,
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            doc_comment: Some(
                "Automatically generated by RURQE. DO NOT EDIT DIRECTLY.\n\n\
                 To synchronize with the database catalog, run `cargo db-codegen`."
                    .to_owned(),
            ),
            generate_records: true,
            type_overrides: BTreeMap::new(),
            domain_types: false,
        }
    }
}

/// Error raised when a catalog cannot be rendered into valid, unambiguous Rust.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CodegenError {
    /// Distinct schema names sanitize into the same Rust identifier.
    IdentifierCollision {
        /// The identifier claimed by more than one schema name.
        ident: String,
        /// The conflicting schema names, in deterministic order.
        sources: Vec<String>,
    },
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CodegenError::IdentifierCollision { ident, sources } => write!(
                f,
                "schema names collide on the generated Rust identifier `{ident}`: {}; \
                 rename them so they differ by more than characters that are invalid in \
                 Rust identifiers",
                sources.join(", ")
            ),
        }
    }
}

impl std::error::Error for CodegenError {}
